#[tokio::test]
async fn test_set_counter() {
    let mut context = program_test().start_with_context().await;

    let authority = Keypair::new();
    let counter_account = Keypair::new();

    // Airdrop
    let tx = Transaction::new_signed_with_payer(
        &[system_instruction::transfer(
            &context.payer.pubkey(),
            &authority.pubkey(),
            1_000_000_000,
        )],
        Some(&context.payer.pubkey()),
        &[&context.payer],
        context.last_blockhash,
    );
    context.banks_client.process_transaction(tx).await.unwrap();

    // Initialize at 50
    let init_ix = instruction::initialize_counter(&id(), &counter_account.pubkey(), &authority.pubkey(), 50);
    let tx = Transaction::new_signed_with_payer(
        &[init_ix],
        Some(&authority.pubkey()),
        &[&authority, &counter_account],
        context.last_blockhash,
    );
    context.banks_client.process_transaction(tx).await.unwrap();

    // Set the counter to 999
    let set_ix = instruction::set_counter(
        &id(),
        &counter_account.pubkey(),
        &authority.pubkey(), // Must match the authority in the account
        999,
    );
    let tx = Transaction::new_signed_with_payer(
        &[set_ix],
        Some(&authority.pubkey()),
        &[&authority],
        context.last_blockhash,
    );
    context.banks_client.process_transaction(tx).await.unwrap();

    // Check
    let account_data = context
        .banks_client
        .get_account(counter_account.pubkey())
        .await
        .unwrap()
        .unwrap();

    let counter_state: CounterState = AnchorDeserialize::try_deserialize(&mut &account_data.data[..])
        .expect("failed to deserialize counter state");

    // Should now be 999
    assert_eq!(counter_state.counter, 999);
    // Should have incremented update_count by 2 (one for init, one for set)
    assert_eq!(counter_state.update_count, 2);
    assert_eq!(counter_state.authority, authority.pubkey());
}
